package com.mycompany.main;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Path;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class MessageTest {

    @TempDir
    Path tempDir;

    // Test data for Message 1 (Task 1)
    private static final String RECIPIENT_1 = "+27718693002";
    private static final String TEXT_1 = "Hi Mike, can you join us for dinner tonight?";

    // Test data for Message 2
    private static final String RECIPIENT_2 = "08575975889";
    private static final String TEXT_2 = "Hi Keegan, did you receive the payment?";

    private Message message1;
    private Message message2;

    @BeforeEach
    void setUp() {
        // The message lists are static, so clear them before every test
        Message.resetMessages();

        // Store to a temporary file so the real JSON file is never touched
        Message.setJsonFile(tempDir.resolve("storedMessages.json").toString());

        // IDs are supplied here so the hashes are predictable
        message1 = new Message("0012345678", 0, RECIPIENT_1, TEXT_1);
        message2 = new Message("0198765432", 1, RECIPIENT_2, TEXT_2);
    }

    // ---------- Message length ----------

    @Test
    void messageLengthSuccess() {
        assertEquals("Message ready to send.", Message.checkMessageLength(TEXT_1));
    }

    @Test
    void messageLengthSuccessAtExactlyTheLimit() {
        String text = "a".repeat(250);
        assertEquals("Message ready to send.", Message.checkMessageLength(text));
    }

    @Test
    void messageLengthFailure() {
        String text = "a".repeat(255);
        assertEquals(
                "Message exceeds 250 characters by 5; please reduce the size.",
                Message.checkMessageLength(text));
    }

    // ---------- Recipient number ----------

    @Test
    void recipientNumberSuccess() {
        assertEquals("Cell phone number successfully captured.",
                Message.checkRecipientCell(RECIPIENT_1));
    }

    @Test
    void recipientNumberFailure() {
        assertEquals(
                "Cell phone number is incorrectly formatted or does not "
                + "contain an international code. Please correct the number "
                + "and try again.",
                Message.checkRecipientCell(RECIPIENT_2));
    }

    // ---------- Message hash ----------

    @Test
    void messageHashIsCorrectForTestCase1() {
        assertEquals("00:0:HITONIGHT", message1.createMessageHash());
    }

    @Test
    void remainingMessageHashesAreCorrect() {
        String[] ids = {"0012345678", "0198765432", "4567890123", "9912345678"};
        int[] numbers = {0, 1, 2, 3};
        String[] texts = {
            TEXT_1,
            TEXT_2,
            "Where are you?",
            "Thanks"
        };
        String[] expected = {
            "00:0:HITONIGHT",
            "01:1:HIPAYMENT",
            "45:2:WHEREYOU",
            "99:3:THANKSTHANKS"
        };

        for (int i = 0; i < ids.length; i++) {
            Message m = new Message(ids[i], numbers[i], RECIPIENT_1, texts[i]);
            assertEquals(expected[i], m.createMessageHash(),
                    "Hash for message " + i);
        }
    }

    // ---------- Message ID ----------

    @Test
    void messageIdIsCreated() {
        assertEquals("Message ID generated: 0012345678",
                message1.returnMessageIDGenerated());
    }

    @Test
    void autoGeneratedMessageIdIsTenDigits() {
        Message m = new Message(RECIPIENT_1, TEXT_1);

        assertTrue(m.checkMessageID());
        assertTrue(m.returnMessageIDGenerated()
                .matches("^Message ID generated: [0-9]{10}$"));
    }

    // ---------- Send, disregard or store ----------

    @Test
    void sendMessageOption1() {
        assertEquals("Message successfully sent.", message1.SentMessage(1));
    }

    @Test
    void disregardMessageOption2() {
        assertEquals("Press 0 to delete the message.", message2.SentMessage(2));
    }

    @Test
    void storeMessageOption3() {
        assertEquals("Message successfully stored.", message1.SentMessage(3));
    }

    // ---------- Total number of messages sent ----------

    @Test
    void totalMessagesSentAfterTestData() {
        message1.SentMessage(1);   // Message 1: Send
        message2.SentMessage(2);   // Message 2: Discard

        assertEquals(1, Message.returnTotalMessages());
    }
}
